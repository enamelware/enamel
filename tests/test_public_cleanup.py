"""Issue #30: public files name no folders on the development machine, and stale lines are fixed.

Folder names are built from parts here, so this file doesn't spell them out.

    scripts/test.sh unit tests.test_public_cleanup
"""
import os, re, subprocess, sys, unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import build_styleguide as sg  # noqa: E402

APP_FOLDER = "kettle" + "-video"
OLD_APP_FOLDER = "media" + "-player"
CASE_STUDY_FOLDER = "enamel" + "-case-" + "study"
# The dated logs keep their history as written.
HISTORY = {"DECISIONS.md", "CHANGELOG.md", "MIGRATION.md"}


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def tracked():
    out = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return [rel for rel in out.splitlines() if os.path.isfile(os.path.join(ROOT, rel))]


def generated_pages():
    return sorted(os.path.basename(path) for path, _ in [(sg.OUT, None)] + sg.other_pages("0"))


class NoPrivateFolders(unittest.TestCase):
    def test_no_tracked_file_names_the_private_folders(self):
        for rel in tracked():
            if rel in HISTORY:
                continue
            try:
                text = read(rel)
            except UnicodeDecodeError:
                continue
            with self.subTest(rel=rel):
                self.assertNotIn(OLD_APP_FOLDER, text)
                self.assertNotIn(CASE_STUDY_FOLDER, text)
                if rel != "scripts/peek.sh":  # the one place that needs it to find the repo
                    self.assertNotIn(APP_FOLDER, text)

    def test_claude_md_describes_the_app_repo_in_words(self):
        claude = read("CLAUDE.md")
        self.assertIn("The Kettle Video repo is read from here only through `scripts/peek.sh`.", claude)
        self.assertNotRegex(claude, r"(?i)kettle video[^.\n]*\bprivate\b")
        self.assertNotIn("as in Kettle Video", claude)
        self.assertNotIn("same delivery workflow as Kettle Video", claude)

    def test_the_launcher_is_described_without_a_location(self):
        for rel in ("CLAUDE.md", "README.md"):
            with self.subTest(rel=rel):
                text = read(rel)
                self.assertIn('a shortcut called "Enamel style guide"', text)
                self.assertNotRegex(text, r"(?i)on the desktop|desktop shortcut|development device")

    def test_peek_looks_only_under_the_current_folder_name(self):
        peek = read("scripts/peek.sh")
        self.assertEqual(peek.count(APP_FOLDER), 1, "one place, where the repo is found")
        self.assertNotRegex(peek, r"\bfor name in\b")


class StaleLines(unittest.TestCase):
    def test_every_list_of_generated_pages_is_complete(self):
        pages = generated_pages()
        self.assertEqual(pages, ["components.html", "index.html", "motion.html", "resize.html"])
        claude_line = next(line for line in read("CLAUDE.md").splitlines() if "fully generated by" in line)
        reviewer_line = next(line for line in read(".claude/agents/reviewer.md").splitlines()
                             if "Generated files are rebuilt" in line)
        readme_line = next(line for line in read("README.md").splitlines() if "`build_styleguide.py` regenerates" in line)
        for name, line in (("CLAUDE.md", claude_line), ("reviewer.md", reviewer_line), ("README.md", readme_line)):
            for page in pages:
                with self.subTest(where=name, page=page):
                    self.assertIn("docs/" + page, line)

    def test_claude_md_says_to_rebuild_the_style_guide_pages(self):
        claude = read("CLAUDE.md")
        self.assertIn("re-run the DESIGN.md script and rebuild the style guide pages in the same commit", claude)
        self.assertNotIn("update docs/index.html", claude)

    def test_the_agent_guard_points_to_an_entry_that_exists(self):
        guard = read(".claude/hooks/agent_guard.py")
        m = re.search(r"DECISIONS\.md \((\d{4}-\d{2}-\d{2}), ([^)]+)\)", guard.replace("\n", " "))
        self.assertIsNotNone(m, "the guard no longer names a DECISIONS.md entry")
        date, title = m.group(1), re.sub(r"\s+", " ", m.group(2))
        self.assertIn(f"## {date}, {title}", read("DECISIONS.md"))


if __name__ == "__main__":
    unittest.main()
