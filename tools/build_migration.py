"""Write MIGRATION.md: every old "kt" name next to its new "en" name (#12).

The rename rules live here, in RULES and FILES, and are the ones the rename
itself used. MIGRATION.md is written from the names the system has now
(tokens and component variables, classes, state attributes, animation names,
behaviour script names, files), each with the old name the rules give back,
so no renamed name is missed. Safe to run any number of times.
Standard library only.

    python3 tools/build_migration.py
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "MIGRATION.md")
TOKENS = os.path.join(ROOT, "tokens", "enamel.css")
COMPONENTS_CSS = os.path.join(ROOT, "components", "enamel-components.css")
COMPONENTS_JS = os.path.join(ROOT, "components", "enamel-components.js")

# Renamed files, old path to new path.
FILES = [("tokens/kettle.css", "tokens/enamel.css"),
         ("components/kettle-components.css", "components/enamel-components.css"),
         ("components/kettle-components.js", "components/enamel-components.js"),
         ("tools/kettle_tokens.py", "tools/enamel_tokens.py")]

# Text rules, old to new, applied in this order. A prefix only counts at the
# start of a name, so "kt" inside a word (Desktop) is left alone.
OLD_PREFIX = r"(?<![A-Za-z0-9_-])(--|data-)?kt-"
RULES = [
    (r"\bkettle\.css\b", "enamel.css"),
    (r"\bkettle-components\b", "enamel-components"),
    (r"\bkettle_tokens\b", "enamel_tokens"),
    (r"\bKettleUI\b", "EnamelUI"),
    (r"__kt([A-Z])", r"__en\1"),
    (OLD_PREFIX, r"\1en-"),
]

HEAD = """# Moving from the kt names to the en names

_Generated by `tools/build_migration.py`, do not edit by hand._

The design system's names changed from the "kt" prefix to "en", and its main
files took the new name. Nothing looks or moves differently: every value is
the same, only the names changed. An app moves over by renaming each old name
below to its new one, in its stylesheets, markup and scripts, and by copying
the files by their new names."""


# Names added after the rename (0.7.0). They never had an old name, so they
# are left out of MIGRATION.md.
ADDED_SINCE = {
    "0.8.0": ["--en-root-size", "--en-size-button", "--en-size-row-control", "--en-size-tile-portrait",
              "--en-space-gutter-grid", "--en-space-icon", "--en-c-menu-width", "--en-c-shelf-gap"],
    "0.9.0": ["en-steplabel", "en-band", "en-band--outline", "en-band__name", "en-band__count", "en-badge",
              "en-row__message", "en-steps"],
    "0.10.0": ["--en-c-statpanel-min", "--en-c-note-gap", "en-statpair", "en-statpanel", "en-statpanel__counts",
               "en-statpanel__count", "en-statpanel__number", "en-statpanel__path", "en-statpanel__notset", "en-note"],
    "0.11.0": ["--en-radius-face", "--en-radius-panel", "--en-cream", "--en-cream-pressed", "--en-satin-light",
               "--en-satin-edge", "--en-satin-shadow", "--en-lift-shadow", "--en-press-shadow", "--en-sunken",
               "--en-focus-underside", "--en-lift", "--en-speckle-fill", "--en-speckle-page", "--en-speckle-page-accent",
               "--en-c-tile-glow", "--en-c-speckle-accent", "--en-c-rise", "--en-c-satin-shadow", "--en-c-lift-shadow",
               "--en-c-press-shadow", "--en-c-focus-stroke", "en-speckle", "data-en-lighter"],
    "0.12.0": ["en-row--destructive", "en-picker__row--destructive"],
}
ADDED = {name for names in ADDED_SINCE.values() for name in names}


def old_name(new):
    """The name the rename gave this new name."""
    for old, renamed in FILES:
        if new == renamed:
            return old
    old = new.replace("EnamelUI", "KettleUI").replace("enamel-components", "kettle-components")
    old = re.sub(r"__en([A-Z])", r"__kt\1", old)
    return re.sub(r"(?<![A-Za-z0-9_-])(--|data-)?en-", r"\1kt-", old)


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def names():
    """(section title, sorted new names) for each kind of renamed name."""
    css = read(TOKENS) + read(COMPONENTS_CSS)
    js = read(COMPONENTS_JS)
    styles = css + js
    return [
        ("Tokens and component variables", sorted(set(re.findall(r"(--en-[a-z0-9-]+)\s*:", css)))),
        ("Component classes", sorted(set(re.findall(r"(?<![\w-])\.(en-[a-z0-9_-]+)", styles))
                                     | set(re.findall(r"className = \"(en-[a-z0-9_-]+)\"", js)))),
        ("State attributes", sorted(set(re.findall(r"\b(data-en-[a-z0-9-]+)", css)))),
        ("Animation names", sorted(set(re.findall(r"@keyframes (en-[a-z0-9-]+)", css)))),
        ("Behaviour script: global, events and element properties",
         sorted(set(re.findall(r"window\.(EnamelUI)\b", js)) | set(re.findall(r"CustomEvent\(\"(en-[a-z-]+)\"", js))
                | set(re.findall(r"\b(__en[A-Z]\w*)", js)))),
        ("Files", [new for _, new in FILES]),
    ]


def page():
    out = [HEAD]
    for title, found in names():
        out += ["", f"## {title}", "", "| Old | New |", "| --- | --- |"]
        out += [f"| `{old_name(n)}` | `{n}` |" for n in found if n not in ADDED]
    return "\n".join(out) + "\n"


def main():
    new = page()
    old = read(OUT) if os.path.exists(OUT) else None
    if new != old:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(new)
        print("MIGRATION.md updated")
    else:
        print("MIGRATION.md already up to date")


if __name__ == "__main__":
    main()
