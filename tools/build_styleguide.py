def e(s):
    return html.escape(str(s), quote=True)


def ms(value):
    v = value.strip()
    return float(v[:-2]) if v.endswith("ms") else float(v[:-1]) * 1000


def sample(kind, name, value=None, groups=None):
    v = f"var({name})"
    if kind == "duration":
        longest = ms(en.resolve(groups, f"var({LONGEST})"))
        return (f'<div class="track"><div class="ruler" style="width: {ms(value) / longest * 100:.4g}%">'
                '</div></div>')
    if kind == "curve":
        return (f'<svg class="curve" viewBox="0 0 100 40" preserveAspectRatio="none" aria-hidden="true">'
                f'<path class="axis" d="M0 40 L100 40"/><path d="{motion_page.curve_path(value)}"/></svg>')
    if kind == "scale":
        return (f'<div class="wrap" style="width: 100%"><div class="track"><div class="ruler" style="width: 80%"></div></div>'
                f'<div class="track" style="margin-top: var(--en-space-tight)"><div class="ruler" '
                f'style="width: calc(80% * {v})"></div></div></div>')
    if kind == "count":
        return '<div class="rings">' + '<span class="ring"></span>' * int(value) + "</div>"
    if kind == "opacity":
        return ('<div class="rings"><span class="ring"></span>'
                f'<span class="ring" style="opacity: {v}"></span></div>')
    if kind == "swatch":
        return f'<div class="frame"><div class="swatch" style="background: {v}; min-height: var(--en-size-row)"></div></div>'
    if kind == "glow":
        return (f'<div class="glow" style="box-shadow: 0 0 var(--en-space-inset) var(--en-space-tight) {v}; '
                f'min-height: var(--en-size-row)"></div>')
    if kind == "text":
        return f'<span style="color: {v}">Recently played</span>'
    if kind == "bar":
        return f'<div class="ruler" style="width: {v}"></div>'
    if kind == "root":
        return '<span class="wrap">Set it on the page\'s root to scale everything, pixels included.</span>'
    if kind == "satin":
        return f'<div class="corner" style="background-color: var(--en-surface-raised); background-image: {v}"></div>'
    if kind == "speckle-fill":
        return f'<div class="swatch" style="width: 100%; min-height: var(--en-space-gap); background-color: var(--en-accent); background-image: {v}"></div>'
