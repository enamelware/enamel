def stamp_version(path, prefix, version):
    """Rewrite the version in a stylesheet's header line, which starts with prefix."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    new, n = re.subn(rf"^( \* {re.escape(prefix)}, version )[^.\s]+(?:\.[0-9A-Za-z-]+)*\.$",
                     lambda m: f"{m.group(1)}{version}.", text, count=1, flags=re.M)
    if n != 1:
        sys.exit(f"{os.path.relpath(path, en.ROOT)}: no ' * {prefix}, version X.' header line")
    return text, new


def write(path, new, old):
    name = os.path.relpath(path, en.ROOT)
    if new != old:
        with open(path, "w", encoding="utf-8") as f:
            f.write(new)
        print(f"{name} updated")
    else:
        print(f"{name} already up to date")


def other_pages(version):
    """The generated pages besides the token reference, as (path, text)."""
    return [(COMPONENTS_OUT, components_page.page(menu(version, "components.html"))),
            (MOTION_OUT, motion_page.page(menu(version, "motion.html"), en.load())),
            (RESIZE_OUT, resize_page.page(menu(version, "resize.html")))]


def main():
    page, results, version = build()
    for path, prefix in STAMPED:
        old, new = stamp_version(path, prefix, version)
        write(path, new, old)
    pages = [(OUT, page)] + other_pages(version)
    for path, new in pages:
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                old = f.read()
        write(path, new, old)
    with open(OVERVIEW, encoding="utf-8") as f:
        old = f.read()
    write(OVERVIEW, put_menu(old, menu(version, "overview.html"), "overview.html"), old)
    for fg, bg, r, text, graphics in results:
        print(f"  {fg:18} on {bg:22} {r:5.2f}:1  text {text:4}  graphics {graphics}")


if __name__ == "__main__":
    main()
