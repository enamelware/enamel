    by_name = {t["name"]: t for t in en.all_tokens(groups)}
    placed = [n for _, _, subs in SECTIONS for _, names, _ in subs for n in names]
    placed += [n for a in en.accents(groups) for n in (a["token"], a["ink"])]
    missing = sorted(set(by_name) - set(placed))
    extra = sorted(set(placed) - set(by_name))
    if missing or extra or len(placed) != len(set(placed)):
        sys.exit(f"style guide sections out of step with enamel.css: missing {missing}, unknown {extra}")
    rules = en.read_rules(DESIGN)
    with open(VERSION, encoding="utf-8") as f:
        version = f.read().strip()
    table, results = contrast_table(groups)

    body = []
    for sid, title, subs in SECTIONS:
        body.append(f'<section id="{sid}"><h2>{e(title)}</h2>')
        if sid == "colour":
            body.append('<p class="lede">The greys and status colours match Steam\'s Gaming Mode. '
                        'The accent is Enamel\'s; these are the active accent tokens that components '
                        'use. The named accents are under <a href="#accents">Accents</a>.</p>')
