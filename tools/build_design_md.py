"""Regenerate DESIGN.md Part 1 (token tables) from tokens/enamel.css.

Replaces only the text between the start and end markers; everything else
in DESIGN.md is hand-written and left alone. Safe to run any number of times.

    python3 tools/build_design_md.py
"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import enamel_tokens as en

DESIGN = os.path.join(en.ROOT, "DESIGN.md")
START = "<!-- enamel-tokens:start (generated by tools/build_design_md.py from tokens/enamel.css, do not edit by hand) -->"
END = "<!-- enamel-tokens:end -->"


def cell(s):
    return s.replace("|", "\\|")


def tables(groups):
    out = ["_Generated, do not edit by hand. Change `tokens/enamel.css`, then run "
           "`python3 tools/build_design_md.py`._", "",
           "Source labels: **Steam baseline** = matched to Steam's Gaming Mode, so Enamel apps "
           "sit naturally beside it; **Enamel** = Enamel's choice.",
           "",
           "A size in rem grows with the user's text size and a size in px does not (see \"Scaling\" below). A value written as "
           "`clamp(base, ..., most)` is its base size on a page up to 100rem wide and grows evenly to "
           "its most, a fifth bigger, at 160rem; it never grows with a narrower page and never shrinks "
           "below its base."]
    for g in groups:
        out += ["", f"### Group {g['key']}: {g['title']}", "",
                "| Token | Value | Source |", "| --- | --- | --- |"]
        for t in g["tokens"]:
            value = f"`{cell(t['value'])}`"
            final = en.resolve(groups, t["value"])
            if final != t["value"]:
                value += f" (= `{cell(final)}`)"
            out.append(f"| `{t['name']}` | {value} | {t['label']} |")
    return "\n".join(out)


def main():
    groups = en.load()
    with open(DESIGN, encoding="utf-8") as f:
        text = f.read()
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        sys.exit("DESIGN.md must contain the start marker once, followed by the end marker once")
    head, rest = text.split(START)
    _, tail = rest.split(END)
    new = f"{head}{START}\n{tables(groups)}\n{END}{tail}"
    if new != text:
        with open(DESIGN, "w", encoding="utf-8") as f:
            f.write(new)
        print("DESIGN.md updated")
    else:
        print("DESIGN.md already up to date")


if __name__ == "__main__":
    main()
